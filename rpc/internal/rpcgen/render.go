package rpcgen

import (
	"bytes"
	"fmt"
	"go/types"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/tools/imports"
)

func (m *model) render(o Options) ([]byte, error) {
	aliases := map[string]string{m.pkg.PkgPath: "contract", "context": "context", "encoding/json": "json"}
	paths := map[string]bool{}
	// Only types appearing in Go expressions need imports. A named struct
	// nested inside another DTO is validated as raw JSON, so importing every
	// recursively visited type would leave unused imports in the output.
	addImports := func(t types.Type) {
		types.TypeString(t, func(p *types.Package) string { paths[p.Path()] = true; return "" })
	}
	for _, method := range m.methods {
		for _, t := range method.args {
			addImports(t)
		}
		if method.result != nil {
			addImports(method.result)
		}
		if method.chunk != nil {
			addImports(method.yield)
			addImports(method.chunk)
		}
	}
	for _, t := range m.types {
		if isRawJSON(t) {
			continue
		}
		if _, alias := t.(*types.Alias); alias {
			continue
		}
		switch u := t.Underlying().(type) {
		case *types.Basic:
			addImports(t)
		case *types.Slice:
			if basic, ok := u.Elem().Underlying().(*types.Basic); ok && basic.Kind() == types.Uint8 {
				addImports(t)
			}
		}
	}
	var extra []string
	for path := range paths {
		if _, ok := aliases[path]; !ok {
			extra = append(extra, path)
		}
	}
	sort.Strings(extra)
	for i, path := range extra {
		aliases[path] = fmt.Sprintf("dto%d", i)
	}
	typeName := func(t types.Type) string {
		return types.TypeString(t, func(p *types.Package) string { return aliases[p.Path()] })
	}
	name := []rune(o.Type)
	name[0] = unicode.ToLower(name[0])
	prefix := string(name)
	handler := "new" + o.Type + "Handler"
	var b bytes.Buffer
	w := func(s string, args ...any) { fmt.Fprintf(&b, s, args...) }
	w("// Code generated by github.com/RussellLuo/gordis/rpc/cmd/rpcgen; DO NOT EDIT.\n\npackage %s\n\n", o.Package)
	w("import (\n\"bytes\"\n\"context\"\n\"encoding/json\"\n\"fmt\"\n\"io\"\nrpc \"github.com/RussellLuo/gordis/rpc\"\ncontract %q\n", m.pkg.PkgPath)
	for _, path := range extra {
		w("%s %q\n", aliases[path], path)
	}
	w(")\n\n// %s binds the ordinary contract using the rpcgen.json/1 wire format.\n", o.Type)
	w("var %s = rpc.NewBinding(contract.%s, \"rpcgen.json/1:\" + string(contract.%s), %sCodec())\n\n", o.Type, o.Key, o.Version, o.Type)
	w("// %sCodec returns a fresh codec for assembly-specific export validation.\n", o.Type)
	w("func %sCodec() rpc.Codec[contract.%s] {\nreturn rpc.Codec[contract.%s]{\n", o.Type, o.Type, o.Type)
	w("Client: func(invoker rpc.Invoker) contract.%s {\nreturn &%sClient{invoker}\n},\nServer: %s,\n}\n}\n\n", o.Type, prefix, handler)
	w("type %sClient struct {\ninvoker rpc.Invoker\n}\n\nvar _ contract.%s = (*%sClient)(nil)\n\n", prefix, o.Type, prefix)
	for _, method := range m.methods {
		w("func (c *%sClient) %s(ctx context.Context", prefix, method.name)
		var args []string
		for i, t := range method.args {
			arg := fmt.Sprintf("a%d", i)
			args = append(args, arg)
			w(", %s %s", arg, typeName(t))
		}
		if method.chunk != nil {
			w(", yield %s) error {\n", typeName(method.yield))
			w("if yield == nil { return fmt.Errorf(%q) }\n\n", method.name+": nil yield")
			w("ctx,cancel := context.WithCancel(ctx)\ndefer cancel()\n\n")
			w("request := struct { Args []any `json:\"args\"` }{Args: []any{%s}}\n\n", strings.Join(args, ","))
			w("return c.invoker.Stream(ctx,%q,request,func(raw json.RawMessage) error {\n", method.name)
			w("fields,err := %sObject(raw)\nif err != nil { return err }\n\n", prefix)
			w("value,ok := fields[\"value\"]\nif !ok || len(fields) != 1 { return fmt.Errorf(%q) }\n", method.name+": expected value chunk field")
			w("if err := %sValidate%d(value); err != nil { return err }\n\n", prefix, m.ids[method.chunk])
			w("var chunk %s\nif err := json.Unmarshal(value,&chunk); err != nil { return err }\nreturn yield(chunk)\n})\n}\n\n", typeName(method.chunk))
			continue
		}
		if method.result == nil {
			w(") error {\n")
		} else {
			w(") (%s,error) {\nvar result %s\n\n", typeName(method.result), typeName(method.result))
		}
		failure := "return err"
		if method.result != nil {
			failure = "return result,err"
		}
		w("request := struct { Args []any `json:\"args\"` }{Args: []any{%s}}\nvar raw json.RawMessage\n", strings.Join(args, ","))
		w("if err := c.invoker.Call(ctx,%q,request,&raw); err != nil { %s }\n\n", method.name, failure)
		w("fields,err := %sObject(raw)\nif err != nil { %s }\n\n", prefix, failure)
		if method.result == nil {
			w("if len(fields) != 0 { return fmt.Errorf(\"%s: expected empty response object\") }\nreturn nil\n}\n\n", method.name)
		} else {
			w("value,ok := fields[\"value\"]\nif !ok || len(fields) != 1 { return result,fmt.Errorf(\"%s: expected value response field\") }\n", method.name)
			w("if err := %sValidate%d(value); err != nil { %s }\n\n", prefix, m.ids[method.result], failure)
			w("err = json.Unmarshal(value,&result)\nreturn result,err\n}\n\n")
		}
	}
	w("func %s(service contract.%s) rpc.Handler {\nreturn rpc.Handler{\nMethods:map[string]rpc.Unary{\n", handler, o.Type)
	for _, stream := range []bool{false, true} {
		if stream {
			w("},\nStreams:map[string]rpc.Stream{\n")
		}
		for _, method := range m.methods {
			if (method.chunk != nil) != stream {
				continue
			}
			failure := "return nil,err"
			if stream {
				w("%q:func(ctx context.Context,raw json.RawMessage,yield func(json.RawMessage)error)error{\n", method.name)
				failure = "return err"
			} else {
				w("%q:func(ctx context.Context,raw json.RawMessage)(json.RawMessage,error){\n", method.name)
			}
			w("args,err := %sArgs(raw,%d)\nif err != nil { %s }\n", prefix, len(method.args), failure)
			if len(method.args) == 0 {
				w("_ = args\n")
			}
			var args []string
			for i, t := range method.args {
				args = append(args, fmt.Sprintf("a%d", i))
				w("\nif err := %sValidate%d(args[%d]); err != nil { err = fmt.Errorf(\"%s argument %d: %%w\",err); %s }\n", prefix, m.ids[t], i, method.name, i, failure)
				w("var a%d %s\nif err := json.Unmarshal(args[%d],&a%d); err != nil { %s }\n", i, typeName(t), i, i, failure)
			}
			call := "service." + method.name + "(ctx"
			if len(args) > 0 {
				call += "," + strings.Join(args, ",")
			}
			if stream {
				w("\nreturn %s,func(chunk %s)error {\n", call, typeName(method.chunk))
				w("raw,err := json.Marshal(struct { Value %s `json:\"value\"` }{Value:chunk})\nif err != nil { return err }\nreturn yield(raw)\n})\n},\n", typeName(method.chunk))
				continue
			}
			call += ")"
			if method.result == nil {
				w("\nif err := %s; err != nil { return nil,err }\nreturn json.RawMessage(`{}`),nil\n},\n", call)
			} else {
				w("\nvalue,err := %s\nif err != nil { return nil,err }\n\nreturn json.Marshal(struct { Value %s `json:\"value\"` }{Value:value})\n},\n", call, typeName(method.result))
			}
		}
	}
	w("},\n}\n}\n")
	// These helpers stay in the generated package. No internal runtime import,
	// reflection, or second schema is needed by downstream builds.
	w("%s", strings.ReplaceAll(wireHelpers, "PREFIX", prefix))
	for id, t := range m.types {
		w("\nfunc %sValidate%d(raw json.RawMessage) error {\n", prefix, id)
		if isRawJSON(t) {
			w("if !json.Valid(raw) { return fmt.Errorf(\"invalid raw JSON value\") }\nreturn nil\n}\n")
			continue
		}
		if a, ok := t.(*types.Alias); ok {
			w("return %sValidate%d(raw)\n}\n", prefix, m.ids[types.Unalias(a)])
			continue
		}
		nullable := false
		switch t.Underlying().(type) {
		case *types.Pointer, *types.Map, *types.Slice:
			nullable = true
		}
		if nullable {
			w("if bytes.Equal(bytes.TrimSpace(raw),[]byte(\"null\")) { return nil }\n\n")
		} else {
			w("if bytes.Equal(bytes.TrimSpace(raw),[]byte(\"null\")) { return fmt.Errorf(%q) }\n\n", "null is invalid for "+types.TypeString(t, func(p *types.Package) string { return p.Name() }))
		}
		switch u := t.Underlying().(type) {
		case *types.Basic:
			w("var value %s\nreturn json.Unmarshal(raw,&value)\n", typeName(t))
		case *types.Pointer:
			w("return %sValidate%d(raw)\n", prefix, m.ids[u.Elem()])
		case *types.Struct:
			w("fields,err := %sObject(raw)\nif err != nil { return err }\nfor name,value := range fields {\n_ = value\nswitch name {\n", prefix)
			for _, f := range m.fields[u] {
				w("case %s: if err := %sValidate%d(value); err != nil { return fmt.Errorf(\"field %%s: %%w\",name,err) }\n", strconv.Quote(f.name), prefix, m.ids[f.typ])
			}
			w("default: return fmt.Errorf(\"unknown DTO field %%q\",name)\n}\n}\nreturn nil\n")
		case *types.Map:
			w("fields,err := %sObject(raw)\nif err != nil { return err }\nfor _,value := range fields { if err := %sValidate%d(value); err != nil { return err } }\nreturn nil\n", prefix, prefix, m.ids[u.Elem()])
		case *types.Array:
			w("var values []json.RawMessage\nif err := json.Unmarshal(raw,&values); err != nil { return err }\nif len(values) != %d { return fmt.Errorf(\"expected array of length %d\") }\n", u.Len(), u.Len())
			w("for _,value := range values { if err := %sValidate%d(value); err != nil { return err } }\nreturn nil\n", prefix, m.ids[u.Elem()])
		case *types.Slice:
			if basic, ok := u.Elem().Underlying().(*types.Basic); ok && basic.Kind() == types.Uint8 {
				// encoding/json represents []byte as base64, not a JSON array.
				w("var value string\nif err := json.Unmarshal(raw,&value); err != nil { return err }\nvar decoded %s\nreturn json.Unmarshal(raw,&decoded)\n", typeName(t))
			} else {
				w("var values []json.RawMessage\nif err := json.Unmarshal(raw,&values); err != nil { return err }\nfor _,value := range values { if err := %sValidate%d(value); err != nil { return err } }\nreturn nil\n", prefix, m.ids[u.Elem()])
			}
		}
		w("}\n")
	}
	// FormatOnly groups imports without resolving packages or changing the
	// explicit imports above. The template owns logical blank lines and wrapping.
	data, err := imports.Process(o.Out, b.Bytes(), &imports.Options{
		FormatOnly: true,
		Comments:   true,
		TabIndent:  true,
		TabWidth:   8,
	})
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return data, nil
}

const wireHelpers = `
// Object enforces a single object with exact field spelling and no duplicates.
func PREFIXObject(raw json.RawMessage) (map[string]json.RawMessage,error) {
 d := json.NewDecoder(bytes.NewReader(raw))
 token,err := d.Token()
 if err != nil { return nil,err }
 if token != json.Delim('{') { return nil,fmt.Errorf("expected JSON object") }

 fields := map[string]json.RawMessage{}
 for d.More() {
  token,err := d.Token()
  if err != nil { return nil,err }
  name,ok := token.(string)
  if !ok { return nil,fmt.Errorf("expected field name") }
  if _,ok := fields[name]; ok { return nil,fmt.Errorf("duplicate field %q",name) }

  var value json.RawMessage
  if err := d.Decode(&value); err != nil { return nil,err }
  fields[name] = value
 }

 if _,err := d.Token(); err != nil { return nil,err }
 if d.Decode(new(json.RawMessage)) != io.EOF { return nil,fmt.Errorf("trailing JSON") }
 return fields,nil
}

func PREFIXArgs(raw json.RawMessage,count int) ([]json.RawMessage,error) {
 fields,err := PREFIXObject(raw)
 if err != nil { return nil,err }

 rawArgs,ok := fields["args"]
 if !ok || len(fields) != 1 { return nil,fmt.Errorf("expected args request field") }
 if bytes.Equal(bytes.TrimSpace(rawArgs),[]byte("null")) { return nil,fmt.Errorf("null args") }

 var args []json.RawMessage
 if err := json.Unmarshal(rawArgs,&args); err != nil { return nil,err }
 if len(args) != count { return nil,fmt.Errorf("expected %d arguments, got %d",count,len(args)) }
 return args,nil
}
`
